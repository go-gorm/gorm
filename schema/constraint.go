package schema

import (
	"regexp"
	"strings"

	"gorm.io/gorm/clause"
)

// regEnLetterAndMidline recognizes ASCII word characters and hyphens in an explicit
// constraint name before the first comma of a tag.
var regEnLetterAndMidline = regexp.MustCompile(`^[\w-]+$`)

// CheckConstraint describes a model check tag. Its expression is trusted SQL evaluated
// by the database during writes; parsing it does not validate the expression or inspect
// existing constraints.
type CheckConstraint struct {
	// Name is the explicit check name or the result of Namer.CheckerName.
	Name string
	// Constraint is the raw SQL predicate, such as length(phone) >= 10. Do not fill it with
	// untrusted input.
	Constraint string // length(phone) >= 10
	// Field identifies the model field declaring the check tag.
	*Field
}

// GetName returns the check-constraint identifier.
func (chk *CheckConstraint) GetName() string { return chk.Name }

// Build returns a CONSTRAINT ... CHECK definition template with a quoted identifier and
// a raw predicate expression. It does not execute DDL.
func (chk *CheckConstraint) Build() (sql string, vars []interface{}) {
	return "CONSTRAINT ? CHECK (?)", []interface{}{clause.Column{Name: chk.Name}, clause.Expr{SQL: chk.Constraint}}
}

// ParseCheckConstraints reads check tags from mapped database fields and returns
// definitions keyed by constraint name. check:name,expression uses an explicit simple
// name; otherwise the naming strategy supplies one. A leading comma selects an unnamed
// expression, and repeated names overwrite earlier map entries.
func (schema *Schema) ParseCheckConstraints() map[string]CheckConstraint {
	checks := map[string]CheckConstraint{}
	for _, field := range schema.FieldsByDBName {
		if chk := field.TagSettings["CHECK"]; chk != "" {
			names := strings.Split(chk, ",")
			if len(names) > 1 && regEnLetterAndMidline.MatchString(names[0]) {
				checks[names[0]] = CheckConstraint{Name: names[0], Constraint: strings.Join(names[1:], ","), Field: field}
			} else {
				if names[0] == "" {
					chk = strings.Join(names[1:], ",")
				}
				name := schema.namer.CheckerName(schema.Table, field.DBName)
				checks[name] = CheckConstraint{Name: name, Constraint: chk, Field: field}
			}
		}
	}
	return checks
}

// UniqueConstraint describes a single-column unique constraint from a unique tag. Index
// tags, including composite unique indexes, are handled by ParseIndexes.
type UniqueConstraint struct {
	// Name is the unique-constraint identifier generated by Namer.UniqueName.
	Name string
	// Field is the column constrained to unique values; NULL handling is database-specific.
	Field *Field
}

// GetName returns the unique-constraint identifier.
func (uni *UniqueConstraint) GetName() string { return uni.Name }

// Build returns a single-column UNIQUE definition template with identifier arguments
// for dialect quoting. It does not execute DDL.
func (uni *UniqueConstraint) Build() (sql string, vars []interface{}) {
	return "CONSTRAINT ? UNIQUE (?)", []interface{}{clause.Column{Name: uni.Name}, clause.Column{Name: uni.Field.DBName}}
}

// ParseUniqueConstraints returns definitions for fields marked Unique, keyed by names
// generated by the naming strategy. It inspects model metadata, not database
// constraints; uniqueIndex tags belong to ParseIndexes.
func (schema *Schema) ParseUniqueConstraints() map[string]UniqueConstraint {
	uniques := make(map[string]UniqueConstraint)
	for _, field := range schema.Fields {
		if field.Unique {
			name := schema.namer.UniqueName(schema.Table, field.DBName)
			uniques[name] = UniqueConstraint{Name: name, Field: field}
		}
	}
	return uniques
}
